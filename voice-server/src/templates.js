// Accepts the app's codes too: "zh-Hans" -> "zh", "es-MX" -> "es".
export function resolveLanguage(code = 'en') {
  const lower = String(code).toLowerCase();
  const base = lower.startsWith('zh') ? 'zh' : lower.split('-')[0];
  return LANGUAGES[base] ? base : null;
}
